#!/usr/bin/env python3
"""Build the arXiv source bundle of the AFM version (arXiv:2607.23500 v2).

Steps:
  1. rebuild paper_afm.tex with latexmk, so that paper_afm.bbl is current;
  2. strip comments with the rules of papers/arxiv/make_arxiv.py:
     - full-line `%` comments are deleted;
     - for inline comments, the text after `%` is dropped but the `%` stays,
       so end-of-line space suppression is unchanged;
     - `lstlisting` / `verbatim` bodies and escaped `\\%` are protected;
     - runs of blank lines are collapsed;
     `\\pdfoutput=1` is added as the first line, as arXiv recommends;
  3. write arxiv/paper_afm.tex and copy arxiv/paper_afm.bbl (arXiv uses the
     supplied .bbl, so the bundle does not need refs.bib);
  4. compile those two files alone in a temporary directory (pdflatex three times)
     and check for errors, undefined references/citations, and the page count
     of the main build;
  5. pack them into arxiv/paper_afm_arxiv.tar.gz;
  6. write arxiv/arxiv_metadata.txt: the form fields, including the abstract
     in arXiv form and its length (limit 1920 characters);
  7. write arxiv/latexmkrc for local previews (not part of the upload). It
     selects pdfLaTeX, since `\\pdfoutput` does not exist in LuaLaTeX, and it
     disables BibTeX: refs.bib is not in arxiv/, so a BibTeX run would
     overwrite the shipped .bbl with an empty bibliography. In VS Code, build
     this file with the "latexmk (latexmkrc)" recipe, because the
     "latexmk (lualatex)" recipe passes -lualatex and overrides the rc file.

Usage (from papers/AFM/):  python make_arxiv.py
Re-run right before every arXiv submission. The arxiv/ directory is output only:
each run deletes it and writes it afresh, which also removes build byproducts.
"""

from __future__ import annotations

import io
import re
import shutil
import subprocess
import tarfile
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "paper_afm.tex"
BBL = HERE / "paper_afm.bbl"
OUT = HERE / "arxiv"
BS = "\\"

VERBATIM_BEGIN = re.compile(r"\\begin\{(lstlisting|verbatim)[*]?\}")
VERBATIM_END = re.compile(r"\\end\{(lstlisting|verbatim)[*]?\}")


def first_comment_pos(line: str) -> int | None:
    """Index of the first unescaped % in `line`, or None."""
    i = 0
    while i < len(line):
        c = line[i]
        if c == BS:
            i += 2  # \% or any escaped character
            continue
        if c == "%":
            return i
        i += 1
    return None


def strip_comments(text: str) -> list[str]:
    out: list[str] = []
    in_verbatim = False
    for line in text.split("\n"):
        if in_verbatim:
            out.append(line)
            if VERBATIM_END.search(line):
                in_verbatim = False
            continue
        if VERBATIM_BEGIN.search(line):
            out.append(line)
            if not VERBATIM_END.search(line):
                in_verbatim = True
            continue
        pos = first_comment_pos(line)
        if pos is not None:
            if line[:pos].strip() == "":
                continue  # full-line comment: drop
            line = line[: pos + 1]  # keep the %, drop the comment text
        out.append(line.rstrip() if not line.endswith("%") else line)
    collapsed: list[str] = []
    verbatim = False
    for line in out:
        if VERBATIM_BEGIN.search(line):
            verbatim = True
        elif VERBATIM_END.search(line):
            verbatim = False
        if not verbatim and line.strip() == "" and collapsed and collapsed[-1].strip() == "":
            continue
        collapsed.append(line)
    return collapsed


def pages_in_log(log: Path) -> int | None:
    m = re.search(r"Output written on \S+ \((\d+) pages", log.read_text(encoding="latin-1"))
    return int(m.group(1)) if m else None


def arxiv_abstract(text: str) -> str:
    a = text.index(BS + "begin{abstract}") + len(BS + "begin{abstract}")
    b = text.index(BS + "end{abstract}")
    body = "\n".join(l for l in text[a:b].split("\n") if not l.lstrip().startswith("%"))
    body = body.replace(BS + "tdensity{C_5}{K_3}", BS + "pi(C_5;K_3)")
    body = body.replace("~", " ")
    paras = [" ".join(p.split()) for p in re.split(r"\n\s*\n", body.strip())]
    return "\n  ".join(paras)  # arXiv: a new paragraph is a line break plus indentation


def main() -> None:
    subprocess.run(["latexmk", "-pdf", "-interaction=nonstopmode", SRC.name], cwd=HERE,
                   check=True, capture_output=True)
    main_pages = pages_in_log(HERE / "paper_afm.log")
    text = io.open(SRC, encoding="utf-8").read()
    lines = strip_comments(text)
    header = [BS + "pdfoutput=1",
              "% arXiv source of the AFM version; generated by papers/AFM/make_arxiv.py."]
    if OUT.exists():
        shutil.rmtree(OUT)  # output only: start clean, dropping any build byproducts
    OUT.mkdir()
    tex_out = OUT / "paper_afm.tex"
    io.open(tex_out, "w", encoding="utf-8", newline="\n").write("\n".join(header + lines) + "\n")
    shutil.copyfile(BBL, OUT / "paper_afm.bbl")

    # stand-alone test build
    with tempfile.TemporaryDirectory() as tmp:
        for f in ("paper_afm.tex", "paper_afm.bbl"):
            shutil.copyfile(OUT / f, Path(tmp) / f)
        for _ in range(3):
            subprocess.run(["pdflatex", "-interaction=nonstopmode", "paper_afm.tex"], cwd=tmp,
                           capture_output=True)
        log = (Path(tmp) / "paper_afm.log").read_text(encoding="latin-1")
        errors = [l for l in log.splitlines() if l.startswith("!")]
        undefined = sorted(set(re.findall(r"(?:Reference|Citation) `([^']+)' .*undefined", log)))
        test_pages = pages_in_log(Path(tmp) / "paper_afm.log")
        remaining = [l for l in (OUT / "paper_afm.tex").read_text(encoding="utf-8").splitlines()
                     if "TODO" in l]
    ok = not errors and not undefined and test_pages == main_pages and not remaining
    print(f"main build: {main_pages} pages; stand-alone arXiv build: {test_pages} pages")
    print(f"errors: {errors or 'none'}; undefined: {undefined or 'none'}; TODO lines left: {len(remaining)}")
    if not ok:
        raise SystemExit("arXiv test build FAILED; bundle not written")

    abstract = arxiv_abstract(text)
    if len(abstract) > 1920:
        raise SystemExit(f"arXiv abstract is too long: {len(abstract)} characters (limit 1920)")

    tarball = OUT / "paper_afm_arxiv.tar.gz"
    with tarfile.open(tarball, "w:gz") as tar:
        for f in ("paper_afm.tex", "paper_afm.bbl"):
            tar.add(OUT / f, arcname=f)

    meta = OUT / "arxiv_metadata.txt"
    meta.write_text(
        "arXiv replacement of 2607.23500 (v2) -- form fields\n"
        "====================================================\n\n"
        "Title: Formalizing Flag Algebras in Lean\n\n"
        "Authors: Gyeongwon Jeong, Seonghun Park, Jihoon Hyun, Sang-il Oum, Hongseok Yang\n\n"
        f"Comments: {main_pages} pages, 1 figure. Lean development: "
        "https://github.com/taeyool/lean-flag-algebras-release (release v1.0)\n\n"
        "MSC classes (suggestion from PLAN.md): 68V20 (primary), 05C35\n\n"
        f"Abstract ({len(abstract)} characters; arXiv limit 1920):\n\n{abstract}\n\n"
        "Upload: paper_afm_arxiv.tar.gz (paper_afm.tex + paper_afm.bbl). arXiv compiles\n"
        "it with pdfLaTeX; the .bbl was produced by BibTeX with plainurl.bst.\n",
        encoding="utf-8")
    latexmkrc = [
        "# Local previews of the arXiv source (not part of the upload).",
        "# pdfLaTeX, as on arXiv: " + BS + "pdfoutput is undefined in LuaLaTeX.",
        "$pdf_mode = 1;",
        "$pdflatex = 'pdflatex %O %S';",
        "# Never run BibTeX here: refs.bib is not in this directory, and a BibTeX",
        "# run would overwrite the shipped paper_afm.bbl.",
        "$bibtex_use = 0;",
    ]
    (OUT / "latexmkrc").write_text("\n".join(latexmkrc) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {tex_out.relative_to(HERE)} ({len(lines)} lines), paper_afm.bbl, "
          f"{tarball.relative_to(HERE)}, {meta.relative_to(HERE)}, arxiv/latexmkrc")
    print(f"abstract: {len(abstract)} characters")


if __name__ == "__main__":
    main()
